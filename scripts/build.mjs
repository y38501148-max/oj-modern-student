import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateSync } from 'node:zlib';
const root = fileURLToPath(new URL('../', import.meta.url));
const channel = process.argv.includes('--edge') ? 'edge' : 'github';
const outArg = process.argv.indexOf('--out');
const out = outArg >= 0 ? resolve(process.argv[outArg + 1]) : resolve(root, 'extension');
const { version } = JSON.parse(await readFile(resolve(root, 'package.json')));
if (!/^\d+\.\d+\.\d+$/.test(version)) throw Error('版本号须为 x.y.z');
await mkdir(out, { recursive: true });
const manifest = {
  manifest_version: 3, name: 'OJ Modern Student', version,
  description: '北航 Accoding 学生端：界面美化、题面和样例复制、提交界面优化。',
  homepage_url: 'https://github.com/y38501148-max/oj-modern-student',
  permissions: ['storage','alarms','clipboardWrite'],
  host_permissions: ['https://raw.githubusercontent.com/*'],
  background: { service_worker: 'background.js', type: 'module' },
  action: { default_title: 'OJ Modern Student', default_popup: 'popup.html', default_icon: { 16: 'icons/16.png', 32: 'icons/32.png' } },
  icons: { 16: 'icons/16.png', 32: 'icons/32.png', 48: 'icons/48.png', 128: 'icons/128.png' },
  content_scripts: [{ matches: ['https://accoding.buaa.edu.cn/*'], css: ['theme.css'], js: ['content.js'], run_at: 'document_idle' }],
  content_security_policy: { extension_pages: "script-src 'self'; object-src 'self'" }
};
await writeFile(resolve(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
await writeFile(resolve(out, 'config.js'), `export const CHANNEL = '${channel}';\n`);
const core = await readFile(resolve(root, 'src/core.mjs'), 'utf8');
const content = await readFile(resolve(root, 'src/content.js'), 'utf8');
await writeFile(resolve(out, 'content.js'), `// Generated by scripts/build.mjs from src/.\n(() => {\n'use strict';\n${core.replace(/^export /gm, '')}\n${content}\n})();\n`);
for (const name of ['core.mjs','background.js','theme.css','popup.html','popup.css','popup.js']) await copyFile(resolve(root, 'src', name), resolve(out, name));
await copyFile(resolve(root, 'LICENSE'), resolve(out, 'LICENSE'));

// Small code-native icon; no external image or runtime dependency.
function crc32(buffer) { let crc = 0xffffffff; for (const byte of buffer) { crc ^= byte; for (let k = 0; k < 8; k++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0); } return (crc ^ 0xffffffff) >>> 0; }
function chunk(type, data) { const name = Buffer.from(type), length = Buffer.alloc(4), checksum = Buffer.alloc(4); length.writeUInt32BE(data.length); checksum.writeUInt32BE(crc32(Buffer.concat([name,data]))); return Buffer.concat([length,name,data,checksum]); }
function icon(size) {
  const lines = [[[.34,.32],[.20,.50]],[[.20,.50],[.34,.68]],[[.66,.32],[.80,.50]],[[.80,.50],[.66,.68]],[[.56,.25],[.44,.75]]];
  const rows = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const px = (x + .5) / size, py = (y + .5) / size;
    const corner = Math.hypot(Math.max(.18 - px,0,px - .82),Math.max(.18 - py,0,py - .82)) <= .18;
    const white = lines.some(([[ax,ay],[bx,by]]) => { const t = Math.max(0,Math.min(1,((px-ax)*(bx-ax)+(py-ay)*(by-ay))/((bx-ax)**2+(by-ay)**2))); return Math.hypot(px-ax-t*(bx-ax),py-ay-t*(by-ay)) < .035; });
    const pos = y * (size * 4 + 1) + 1 + x * 4;
    rows.set(white ? [255,255,255,corner?255:0] : [39,90,214,corner?255:0], pos);
  }
  const header = Buffer.alloc(13); header.writeUInt32BE(size); header.writeUInt32BE(size,4); header[8] = 8; header[9] = 6;
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),chunk('IHDR',header),chunk('IDAT',deflateSync(rows)),chunk('IEND',Buffer.alloc(0))]);
}
await mkdir(resolve(out, 'icons'), { recursive:true });
for (const size of [16,32,48,128]) await writeFile(resolve(out, `icons/${size}.png`), icon(size));
// Version metadata is public data, never executable update code.
if (out === resolve(root, 'extension')) await writeFile(resolve(root, 'version.json'), JSON.stringify({ version }, null, 2) + '\n');
console.log(`Built ${channel} v${version}: ${out}`);
